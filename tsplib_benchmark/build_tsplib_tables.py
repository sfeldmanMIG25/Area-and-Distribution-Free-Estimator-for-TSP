"""
Emit the TSPLIB LaTeX tables the paper \\input's, matching the paper's
multirow + resizebox aesthetic but with SDPE as the primary column,
bootstrap CI, and numbers pulled from the merged canonical + supplemental
benchmark CSVs.
"""
import os
import numpy as np
import pandas as pd
from sklearn.metrics import r2_score

ROOT    = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
RESULTS = os.path.join(ROOT, 'tsplib_benchmark', 'results')
GEN_DIR = os.path.join(ROOT, 'paper_reference', 'gen')
os.makedirs(GEN_DIR, exist_ok=True)

CANONICAL  = os.path.join(RESULTS, 'all_models_tsplib.csv')
SUPPLEMENT = os.path.join(RESULTS, 'all_models_tsplib_supplemental.csv')
MERGED     = os.path.join(RESULTS, 'all_models_tsplib_merged.csv')

HEADLINE_MODELS = ['LGBM_V3', 'MST_Ratio', 'Cavdar', 'BHH', 'Chien', 'Hilbert']
MODEL_LABEL = {
    'LGBM_V3':   'GART 2.0',
    'MST_Ratio': 'MST Ratio',
    'Cavdar':    'Cavdar',
    'BHH':       'BHH',
    'Chien':     'Chien',
    'Hilbert':   'Hilbert',
    'Vinel':     'Vinel',
}

# Paper buckets keep instance counts balanced.
PAPER_BUCKETS = [
    ('$[51,\\,150]$',    51,    150),
    ('$[151,\\,400]$',   151,   400),
    ('$[401,\\,1500]$',  401,   1500),
    ('$n > 1500$',       1501,  10**9),
]


def bootstrap_sdpe_ci(rel, n_boot=1000, seed=42):
    v = rel.to_numpy()
    if len(v) < 3:
        return (np.nan, np.nan)
    rng = np.random.default_rng(seed)
    sdpes = np.empty(n_boot)
    for i in range(n_boot):
        sdpes[i] = v[rng.integers(0, len(v), len(v))].std(ddof=1) * 100
    return tuple(np.percentile(sdpes, [2.5, 97.5]))


def agg(df, model_key):
    if len(df) == 0:
        return None
    rel = df['gap_pct'] / 100.0
    out = dict(
        N      = len(df),
        SDPE   = rel.std(ddof=1) * 100 if len(df) > 1 else np.nan,
        MAPE   = df['abs_gap_pct'].mean(),
        MEDIAN = df['abs_gap_pct'].median(),
        TIME   = df['total_time_s'].mean() * 1000,
    )
    lo, hi = bootstrap_sdpe_ci(rel)
    out['SDPE_LO'], out['SDPE_HI'] = lo, hi
    try:
        out['R2'] = r2_score(df['true_cost'], df['pred_cost'])
    except Exception:
        out['R2'] = np.nan
    if model_key == 'LGBM_V3' and 'alpha' in df.columns and 'mst_length' in df.columns:
        pred_alpha = df['alpha']
        true_alpha = df['true_cost'] / df['mst_length']
        mask = pred_alpha.notna() & true_alpha.notna() & (pred_alpha.std() > 0)
        if mask.sum() > 2:
            out['R_ALPHA'] = pred_alpha[mask].corr(true_alpha[mask])
        else:
            out['R_ALPHA'] = np.nan
    else:
        out['R_ALPHA'] = None
    return out


def f(x, s='{:.2f}'):
    return '---' if (x is None or (isinstance(x, float) and np.isnan(x))) else s.format(x)


def sdpe_cell(r):
    if r is None or np.isnan(r['SDPE']):
        return '---'
    return f"{r['SDPE']:.2f}~{{\\scriptsize[{r['SDPE_LO']:.2f},{r['SDPE_HI']:.2f}]}}"


def optimal_time_cell(bucket, use_concorde=True):
    t = bucket['concorde_time_s'].dropna()
    if len(t) > 0:
        mean_ms = t.mean() * 1000
        return f"${mean_ms:.1e}$~ms".replace('e+0', r'\times 10^{').replace('e+', r'\times 10^{') + '}'
    return '---'


def sci_ms(ms):
    """Format a millisecond value in scientific LaTeX ($a.b\\times 10^{c}$ ms)."""
    if ms is None or np.isnan(ms) or ms <= 0:
        return '---'
    exp = int(np.floor(np.log10(ms)))
    mant = ms / 10**exp
    return f"${mant:.1f}\\times 10^{{{exp}}}$~ms"


def model_row(label, r, is_gart):
    bopen, bclose = (r"\textbf{", "}") if is_gart else ("", "")
    return (
        f"  & {bopen}{label}{bclose} & "
        f"{bopen}{sdpe_cell(r)}{bclose} & "
        f"{bopen}{f(r['MAPE'] if r else None)}{bclose} & "
        f"{f(r['MEDIAN'] if r else None)} & "
        f"{f(r['R2'] if r else None, '{:.3f}')} & "
        f"{f(r['R_ALPHA'] if (r and r['R_ALPHA'] is not None) else None, '{:.3f}')} & "
        f"{f(r['TIME'] if r else None, '{:.2f}')} & "
        f"{r['N'] if r else '---'} \\\\"
    )


def optimal_row(bucket_df):
    t_ms = np.nan
    concorde = bucket_df[bucket_df['model'] == 'LGBM_V3']['concorde_time_s'].dropna()
    if len(concorde) > 0:
        t_ms = concorde.mean() * 1000
    return f"  & \\textit{{Optimal solver}} & --- & --- & --- & --- & --- & {sci_ms(t_ms)} & --- \\\\"


def build_by_size_table(df, out_path):
    nmodels = len(HEADLINE_MODELS)
    multirow_size = nmodels + 1  # +1 for Optimal solver row
    L = [
        r"% Auto-generated by tsplib_benchmark/build_tsplib_tables.py. Do not edit.",
        r"\begin{tabular}{@{}ll rrrrrrr@{}}",
        r"\toprule",
        r"$n$ bucket & Model & SDPE (\%) [95\% CI] & MAPE (\%) & Median (\%) & $R^2$ & $r_\alpha$ & Time (ms) & $N$ \\",
        r"\midrule",
    ]
    for (lbl, lo_n, hi_n) in PAPER_BUCKETS:
        bucket = df[(df['n'] >= lo_n) & (df['n'] <= hi_n)]
        L.append(r"\multirow{" + str(multirow_size) + r"}{*}{" + lbl + r"}")
        for m in HEADLINE_MODELS:
            r = agg(bucket[bucket['model'] == m], m)
            L.append(model_row(MODEL_LABEL[m], r, is_gart=(m == 'LGBM_V3')))
        L.append(optimal_row(bucket))
        L.append(r"\midrule")
    # Total
    total = df[df['n'] >= 51]
    L.append(r"\multirow{" + str(multirow_size) + r"}{*}{\textbf{Total}}")
    for m in HEADLINE_MODELS:
        r = agg(total[total['model'] == m], m)
        L.append(model_row(MODEL_LABEL[m], r, is_gart=(m == 'LGBM_V3')))
    L.append(optimal_row(total))
    L += [r"\bottomrule", r"\end{tabular}"]
    with open(out_path, 'w', encoding='utf-8') as f_:
        f_.write('\n'.join(L) + '\n')


def build_by_model_table(df, out_path):
    L = [
        r"% Auto-generated by tsplib_benchmark/build_tsplib_tables.py. Do not edit.",
        r"\begin{tabular}{l rrrrrrr}",
        r"\toprule",
        r"Model & SDPE (\%) [95\% CI] & MAPE (\%) & Median (\%) & $R^2$ & $r_\alpha$ & Time (ms) & $N$ \\",
        r"\midrule",
    ]
    for m in HEADLINE_MODELS:
        r = agg(df[df['model'] == m], m)
        L.append(model_row(MODEL_LABEL[m], r, is_gart=(m == 'LGBM_V3')).lstrip(' &').strip())
    L += [r"\bottomrule", r"\end{tabular}"]
    with open(out_path, 'w', encoding='utf-8') as f_:
        f_.write('\n'.join(L) + '\n')


def main():
    can = pd.read_csv(CANONICAL)
    sup = pd.read_csv(SUPPLEMENT)
    merged = pd.concat([can, sup], ignore_index=True).drop_duplicates(subset=['instance', 'model'], keep='first')
    merged.to_csv(MERGED, index=False)

    euc2d = merged[merged['edge_weight_type'] == 'EUC_2D'].copy()
    print(f"Merged rows: {len(merged)} | EUC_2D rows: {len(euc2d)} | instances: {euc2d['instance'].nunique()}")

    build_by_size_table(euc2d, os.path.join(GEN_DIR, 'tsplib_by_size.tex'))
    build_by_model_table(euc2d, os.path.join(GEN_DIR, 'tsplib_by_model.tex'))
    print(f"Wrote {GEN_DIR}/tsplib_by_size.tex and tsplib_by_model.tex")

    g = agg(euc2d[euc2d['model'] == 'LGBM_V3'], 'LGBM_V3')
    print(f"GART 2.0 EUC_2D: SDPE={g['SDPE']:.2f} [{g['SDPE_LO']:.2f},{g['SDPE_HI']:.2f}] | "
          f"MAPE={g['MAPE']:.2f} | MED={g['MEDIAN']:.2f} | R2={g['R2']:.3f} | r_a={g['R_ALPHA']:.3f} | N={g['N']}")


if __name__ == '__main__':
    main()
